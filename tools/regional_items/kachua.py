#!/usr/bin/env python3
"""Put the newest Overseas Care Package's drops in Kachua's Secret Box.

Kachua's Secret Box (Main_Lucky_Box, opened with a Kachua's Secret Key) and
the [Reward] Kachua's Secret Key (Main_Lucky_Box_) draw from kRO kits of
their own. This reads the newest OCP_<MONTH>_<YEAR> entry that generate.py
wrote to db/re/item_db_regional.yml and adds each of its drops to both
groups at Rate 1, the lowest chance either group has, in
db/re/item_group_db_regional.yml. Run it after generate.py, so a client with
a newer OCP moves the boxes to it.

    tools/regional_items/kachua.py [--items db/re/item_db_regional.yml]
                                   [--out db/re/item_group_db_regional.yml]
"""
import argparse
import re

MONTHS = {m: i for i, m in enumerate(
    ['JAN', 'FEB', 'MAR', 'APR', 'MAY', 'JUN', 'JUL', 'AUG', 'SEP', 'OCT', 'NOV', 'DEC'], 1)}
GROUPS = ['MAIN_LUCKY_BOX', 'MAIN_LUCKY_BOX_']
SUBGROUP = 6        # the random draw in both groups (subgroup 0 is the Mileage Coupon every opening gives)
FIRST_INDEX = 1000  # past the groups' own Index values


def aegis_names(paths):
    """Item id -> AegisName, from the item_db files."""
    names, cur = {}, None
    for path in paths:
        for line in open(path, encoding='utf-8'):
            m = re.match(r'  - Id: (\d+)$', line)
            if m:
                cur = int(m.group(1))
                continue
            m = re.match(r'    AegisName: (\S+)$', line)
            if m and cur is not None:
                names[cur] = m.group(1)
                cur = None
    return names


def newest_ocp(path):
    """(aegis, [(item id, amount, aegis of the item)]) of the newest OCP."""
    best, cur = None, None
    for line in open(path, encoding='utf-8'):
        m = re.match(r'    AegisName: (OCP_([A-Z]{3})[A-Z]*_(\d{4}))$', line)
        if m and m.group(2) in MONTHS:
            cur = (int(m.group(3)), MONTHS[m.group(2)], m.group(1), [])
            if best is None or cur[:2] > best[:2]:
                best = cur
            continue
        if re.match(r'  - Id: ', line):
            cur = None
        elif cur is not None:
            g = re.search(r'getitem (\d+),(\d+);\s*// (\S+)', line)
            if g:
                cur[3].append((int(g.group(1)), int(g.group(2)), g.group(3)))
    if best is None or not best[3]:
        raise SystemExit('no Overseas Care Package with a readable draw in %s' % path)
    return best[2], best[3]


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--items', default='db/re/item_db_regional.yml')
    ap.add_argument('--out', default='db/re/item_group_db_regional.yml')
    a = ap.parse_args()
    ocp, drops = newest_ocp(a.items)
    names = aegis_names([a.items] + ['db/re/item_db_%s.yml' % t for t in ('usable', 'equip', 'etc')])
    missing = [i for i, _, _ in drops if i not in names]
    if missing:
        raise SystemExit('no AegisName for %s' % missing)
    drops = [(i, n, names[i]) for i, n, _ in drops]
    out = ['# GENERATED by tools/regional_items/kachua.py from %s (%s). Do not edit by hand.' % (ocp, a.items),
           '# Every drop of the newest Overseas Care Package, at the lowest chance (Rate 1),',
           "# in Kachua's Secret Box and the [Reward] Kachua's Secret Key.",
           '', 'Header:', '  Type: ITEM_GROUP_DB', '  Version: 5', '', 'Body:']
    for group in GROUPS:
        out += ['  - Group: %s' % group, '    SubGroups:', '      - SubGroup: %d' % SUBGROUP, '        List:']
        for k, (item, amount, aegis) in enumerate(drops):
            out += ['          - Index: %d' % (FIRST_INDEX + k), '            Item: %s' % aegis]
            if amount > 1:
                out.append('            Amount: %d' % amount)
            out += ['            Rate: 1', '            Announced: true' if amount == 1 else '            Announced: false']
    open(a.out, 'w', encoding='utf-8').write('\n'.join(out) + '\n')
    print('%s: %d drops of %s in %s' % (a.out, len(drops), ocp, ', '.join(GROUPS)))


if __name__ == '__main__':
    main()
